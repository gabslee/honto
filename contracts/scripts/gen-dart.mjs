// OpenAPI -> Dart models (models.g.dart) + API interface and HTTP client (api.g.dart).
import { describe, isClientOp, operations, schemaKind, typeName } from "./spec.mjs";

const HEADER = "// GENERATED by contracts/scripts/generate.mjs from contracts/openapi.yaml. Do not edit by hand.\n// ignore_for_file: type=lint, unnecessary_non_null_assertion\n";
const camel = (wire) => {
  const parts = String(wire).split(/[^A-Za-z0-9]+/).filter(Boolean);
  const id = parts.map((p, i) => (i === 0 ? p[0].toLowerCase() + p.slice(1) : p[0].toUpperCase() + p.slice(1))).join("");
  return /^[0-9]/.test(id) ? `v${id}` : id;
};
const dartDoc = (text, indent = "") => (text ? String(text).trim().split("\n").map((l) => `${indent}/// ${l}`).join("\n") + "\n" : "");
const dartStr = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;

export function generateDart(spec) {
  const schemas = spec.components.schemas;
  const included = Object.entries(schemas).filter(([, s]) => s["x-dart"] !== false);
  const kindOf = (name) => schemaKind(schemas[name]);

  const dartType = (d) => {
    let t;
    switch (d.kind) {
      case "ref": t = typeName(d.name); break;
      case "array": t = `List<${dartType(d.items)}>`; break;
      case "map": t = `Map<String, ${dartType(d.values)}>`; break;
      case "unknown": return "Object?";
      case "datetime": t = "DateTime"; break;
      case "string": t = "String"; break;
      case "int": t = "int"; break;
      case "double": t = "double"; break;
      case "bool": t = "bool"; break;
    }
    return d.nullable ? `${t}?` : t;
  };
  const fromExpr = (d, src) => {
    const nn = (() => {
      switch (d.kind) {
        case "ref": {
          const k = kindOf(d.name);
          if (k === "enum") return `${typeName(d.name)}.fromJson(${src} as String)`;
          if (k === "object") return `${typeName(d.name)}.fromJson(${src} as Map<String, dynamic>)`;
          return fromExpr({ ...describe(schemas[d.name]), nullable: false }, src);
        }
        case "array": return `(${src} as List<dynamic>).map((e) => ${fromExpr(d.items, "e")}).toList()`;
        case "map": return d.values.kind === "unknown" ? `Map<String, Object?>.from(${src} as Map)` : `(${src} as Map<String, dynamic>).map((k, e) => MapEntry(k, ${fromExpr(d.values, "e")}))`;
        case "datetime": return `DateTime.parse(${src} as String)`;
        case "string": return `${src} as String`;
        case "int": return `(${src} as num).toInt()`;
        case "double": return `(${src} as num).toDouble()`;
        case "bool": return `${src} as bool`;
        case "unknown": return src;
      }
    })();
    return d.nullable ? `${src} == null ? null : ${nn}` : nn;
  };
  const toExpr = (d, v) => {
    const val = d.nullable ? `${v}!` : v;
    const nn = (() => {
      switch (d.kind) {
        case "ref": { const k = kindOf(d.name); return k === "alias" ? val : `${val}.toJson()`; }
        case "array": return `${val}.map((e) => ${toExpr(d.items, "e")}).toList()`;
        case "map": return d.values.kind === "unknown" ? val : `${val}.map((k, e) => MapEntry(k, ${toExpr(d.values, "e")}))`;
        case "datetime": return `${val}.toUtc().toIso8601String()`;
        default: return val;
      }
    })();
    if (nn === val) return v;
    return d.nullable ? `${v} == null ? null : ${nn}` : nn;
  };

  const m = [HEADER, "import 'json_support.dart';", ""];
  for (const [name, schema] of included) {
    const tn = typeName(name);
    const kind = schemaKind(schema);
    if (schema.description) m.push(dartDoc(schema.description).trimEnd());
    if (kind === "enum") {
      const members = schema.enum.map((v) => `  ${camel(v)}(${dartStr(v)})`);
      m.push(`enum ${tn} {`, members.join(",\n") + ",", "  /// A value added to the API after this client was built.", "  unrecognized('');", "",
        `  const ${tn}(this.wire);`, "  final String wire;", "",
        `  static ${tn} fromJson(String value) => values.firstWhere((e) => e.wire == value && e != unrecognized, orElse: () => unrecognized);`,
        "  String toJson() => wire;", "}", "");
      continue;
    }
    if (kind === "alias") {
      const d = describe(schema);
      m.push(`typedef ${tn} = ${dartType(d)};`, "");
      continue;
    }
    const required = new Set(schema.required ?? []);
    const props = Object.entries(schema.properties ?? {}).map(([prop, ps]) => {
      const d = describe(ps);
      const req = required.has(prop);
      const patch = !req && d.nullable && schema["x-patch"] === true;
      const base = dartType(d);
      const type = req ? base : patch ? `Nullable<${dartType({ ...d, nullable: false })}>?` : `${dartType({ ...d, nullable: false })}?`;
      return { prop, ps, d, req, patch, type };
    });
    m.push(`class ${tn} {`);
    m.push(props.length ? `  const ${tn}({${props.map((p) => `${p.req ? "required " : ""}this.${p.prop}`).join(", ")}});` : `  const ${tn}();`, "");
    for (const p of props) {
      const extra = p.patch ? "Omit (null) to keep the current value; `Nullable(null)` clears it." : "";
      const docText = [p.ps.description, extra].filter(Boolean).join(" ");
      if (docText) m.push(dartDoc(docText, "  ").trimEnd());
      m.push(`  final ${p.type} ${p.prop};`);
    }
    m.push("");
    m.push(`  factory ${tn}.fromJson(Map<String, dynamic> json) => ${tn}(`);
    for (const p of props) {
      const src = `json[${dartStr(p.prop)}]`;
      let expr;
      if (p.req) expr = fromExpr(p.d, src);
      else if (p.patch) expr = `json.containsKey(${dartStr(p.prop)}) ? Nullable(${fromExpr(p.d, src)}) : null`;
      else expr = fromExpr({ ...p.d, nullable: true }, src);
      m.push(`        ${p.prop}: ${expr},`);
    }
    m.push("      );", "");
    m.push("  Map<String, dynamic> toJson() => <String, dynamic>{");
    for (const p of props) {
      const key = dartStr(p.prop);
      if (p.req) m.push(`        ${key}: ${toExpr(p.d, p.prop)},`);
      else if (p.patch) m.push(`        if (${p.prop} != null) ${key}: ${toExpr({ ...p.d, nullable: true }, `${p.prop}!.value`)},`);
      else m.push(`        if (${p.prop} != null) ${key}: ${toExpr({ ...p.d, nullable: false }, `${p.prop}!`)},`);
    }
    m.push("      };", "");
    m.push("  @override", `  String toString() => '${tn}(\${toJson()})';`, "}", "");
  }

  m.push("/// Decoders for every object model, keyed by Dart type name (used by fakes and fixture tests).");
  m.push("final Map<String, Object Function(Map<String, dynamic>)> hontoModelDecoders = <String, Object Function(Map<String, dynamic>)>{");
  for (const [name, schema] of included) if (schemaKind(schema) === "object") m.push(`  '${typeName(name)}': ${typeName(name)}.fromJson,`);
  m.push("};", "");

  // API interface + HTTP implementation.
  const ops = operations(spec).filter(isClientOp);
  const a = [HEADER, "import 'json_support.dart';", "import 'models.g.dart';", ""];
  const sig = (op) => {
    const params = op.pathParams.map((p) => `String ${p.name}`);
    if (op.body) params.push(`${typeName(op.body)} body`);
    const named = op.queryParams.map((p) => `${p.required ? "required " : ""}String${p.required ? "" : "?"} ${p.name}`);
    const ret = op.successSchema ? typeName(op.successSchema) : "void";
    return `Future<${ret}> ${op.id}(${params.join(", ")}${named.length ? `${params.length ? ", " : ""}{${named.join(", ")}}` : ""})`;
  };
  a.push("/// Every client-facing operation of `/api/v1`. Implemented by [HttpHontoApi] and by the hand-written `FakeHontoApi`.");
  a.push("abstract class HontoApi {");
  for (const op of ops) {
    a.push(`  /// \`${op.method} ${op.path}\`: ${op.summary}`);
    a.push(`  ${sig(op)};`, "");
  }
  a.push("}", "");
  a.push("/// Real implementation over [HontoTransport] (bearer token, JSON, error mapping).");
  a.push("class HttpHontoApi implements HontoApi {");
  a.push("  HttpHontoApi(this.transport);", "  final HontoTransport transport;", "");
  for (const op of ops) {
    let path = dartStr(op.path);
    for (const p of op.pathParams) path = path.replace(`{${p.name}}`, `\${Uri.encodeComponent(${p.name})}`);
    const query = op.queryParams.length ? `, query: {${op.queryParams.map((p) => p.required ? `${dartStr(p.name)}: ${p.name}` : `if (${p.name} != null) ${dartStr(p.name)}: ${p.name}`).join(", ")}}` : "";
    const body = op.body ? ", body: body.toJson()" : "";
    const ret = op.successSchema ? typeName(op.successSchema) : null;
    a.push("  @override");
    a.push(`  ${sig(op)} async {`);
    a.push(`    ${ret ? "final json = " : ""}await transport.send(${dartStr(op.method)}, ${path}${query}${body});`);
    if (ret) a.push(`    return ${ret}.fromJson(json as Map<String, dynamic>);`);
    a.push("  }", "");
  }
  a.push("}", "");
  const clean = (arr) => arr.join("\n").replace(/\n{3,}/g, "\n\n");
  return { models: clean(m), api: clean(a) };
}
